#!/usr/bin/env python3
"""Generate or check THIRD_PARTY_LICENSES.md from `cargo metadata`.

    python3 scripts/third_party_licenses.py          # rewrite THIRD_PARTY_LICENSES.md
    python3 scripts/third_party_licenses.py --check  # exit 1 if the file is out of date

The list covers every crate in Cargo.lock (all features, all target platforms) that is not
a workspace member. It records the licence expression each crate declares in its own
metadata; it does not reproduce the licence texts or copyright notices of those crates.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_LICENSES.md"

HEADER = """# Third-party licences

GQODB itself is licensed under the Apache License, Version 2.0 (see `LICENSE`).
This file lists the third-party Rust crates that appear in `Cargo.lock`, with the licence
expression each crate declares in its own `Cargo.toml`. It is generated by
`scripts/third_party_licenses.py` from `cargo metadata --locked --all-features`, so it
includes the optional `zstd-input` feature and dependencies of every target platform
(Linux, macOS, Windows, WebAssembly), not only those compiled on one machine.

What this file is not: it does not reproduce the licence texts or copyright notices of
these crates, and the declared expressions are the crates' own claims, not a legal review.
The source repository does not redistribute these crates; the build downloads them from
crates.io. If you redistribute binaries built from this source, collect the notices of the
crates that were actually linked (for example with `cargo about`), and check the licence
choice for dual-licensed crates yourself. `cargo deny check` (see `deny.toml`) enforces the
allowed licence set in CI.

Regenerate with `python3 scripts/third_party_licenses.py`; CI runs it with `--check`.

| Crate | Version | Declared licence | Source |
| --- | --- | --- | --- |
"""


def render() -> str:
    raw = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--all-features"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    packages = [p for p in json.loads(raw)["packages"] if p.get("source")]
    packages.sort(key=lambda p: (p["name"], p["version"]))
    rows = []
    for p in packages:
        licence = (p.get("license") or "(none declared)").replace("|", "\\|")
        repo = p.get("repository") or f"https://crates.io/crates/{p['name']}"
        rows.append(f"| `{p['name']}` | {p['version']} | {licence} | <{repo}> |")
    return HEADER + "\n".join(rows) + f"\n\n{len(rows)} crates.\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print("THIRD_PARTY_LICENSES.md is out of date; run scripts/third_party_licenses.py")
            return 1
        print(f"THIRD_PARTY_LICENSES.md is up to date ({text.count(chr(10) + '| `')} crates)")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
